// interpolate finds the first calibrated point below the raw reading and
// interpolates linearly between it and the one above. A reading above the top
// of the table takes the top point's value rather than being extrapolated.
func interpolate(table []calibration, raw uint16) int32 {
	index := len(table) - 1
	for candidate := 0; candidate < len(table)-1; candidate++ {
		if table[candidate].raw < raw {
			index = candidate
			break
		}
	}
	if index == 0 {
		return table[0].value
	}
	above, below := table[index-1], table[index]
	value := (int32(raw) - int32(below.raw)) * above.value
	value += (int32(above.raw) - int32(raw)) * below.value
	return value / (int32(above.raw) - int32(below.raw))
}
