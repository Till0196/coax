// intLog2 returns log2(x) scaled by 2^24. The fractional part comes from the
// table rather than the remainder directly: log2(1+f) is not f, and treating
// it as such is the approximation this deliberately does not make.
func intLog2(x uint32) uint32 {
	if x == 0 {
		return 0
	}
	msb := uint(31 - bits.LeadingZeros32(x))
	significand := x << (31 - msb)
	entry := significand >> 23 % 256
	next := logTable[(entry+1)%256]
	interpolation := (significand & 0x7fffff) * uint32(uint16(next-logTable[entry])) >> 15
	return uint32(msb)<<24 + uint32(logTable[entry])<<8 + interpolation
}

// intLog10 returns log10(x) scaled by 2^24, as log2(x) times log10(2).
func intLog10(x uint32) uint32 {
	return uint32(uint64(intLog2(x)) * 646456993 >> 31)
}

// MathLog10 returns log10(x) x 100.
func MathLog10(x uint32) uint32 {
	return uint32(uint64(intLog10(x)) * 100 >> 24)
}

// MathLog returns ln(x) x 100. It is derived from log2 rather than log10
// because the J.83 and satellite curves are expressed in natural logarithms,
// and going through log10 would round twice.
func MathLog(x uint32) uint32 {
	const log2OfEHundredths = 144
	return ((10000>>8)*(intLog2(x)>>16) + log2OfEHundredths/2) / log2OfEHundredths
}
