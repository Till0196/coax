package rda5816

// Named registers; everything else is written once from the tables below.
const (
	// 0x00/0x01 carry a twelve-bit chip identifier and a four-bit revision,
	// split across a nibble boundary.
	registerChipID   = 0x00
	registerRevision = 0x01
	// Low two bits are the PLL's two lock indications; both must be set.
	registerLock    = 0x03
	registerControl = 0x04
	// First of the four divider-word bytes, most significant first.
	registerPLL = 0x07
	// Channel filter bandwidth in megahertz.
	registerFilter = 0x0b
	// Holds both the high/low band choice and the RF input switch, so every
	// write to it is a read-modify-write.
	registerBand = 0x65
)

// Values and bit fields.
const (
	// The soft reset is asserted and released by writing these two in turn.
	controlResetAssert  = 0x04
	controlResetRelease = 0x05
	// controlEnable is the bit that brings a half up; controlEnableChannel is
	// written over the whole register by the half being initialized.
	controlEnable        = 0x80
	controlEnableChannel = 0x85
	// controlLoad is written before the divider and filter go in, controlTune
	// afterwards to start the synthesizer on them.
	controlLoad = 0xc1
	controlTune = 0xc3

	lockMask = 0x03

	// Band bits in registerBand: high band above bandSplitMHz, low band below
	// it with the PLL asked for twice the frequency.
	bandHigh = 0x10
	bandLow  = 0x08
	// The RF input switch, set on the half that takes the input, cleared on
	// the other.
	rfSwitchMask = 0x06

	// filterEnable sits above the bandwidth field, filterMask is the field.
	filterEnable = 0x40
	filterMask   = 0x3f
)

